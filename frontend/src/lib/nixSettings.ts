import type { ShaderValue } from '../generated/protocol';

/** A number as written, so `0.50` keeps its decimals and `18.0` stays a float. */
export class NumberText {
  constructor(readonly text: string) {}
}

export type SettingValue =
  | Exclude<ShaderValue, Array<ShaderValue> | Record<string, ShaderValue>>
  | NumberText
  | SettingValue[]
  | { [key: string]: SettingValue };

const KEYWORDS = new Set(['assert', 'else', 'if', 'in', 'inherit', 'let', 'or', 'rec', 'then', 'with']);

function nixString(value: string): string {
  const escaped = value
    .replace(/\\/g, '\\\\')
    .replace(/"/g, '\\"')
    .replace(/\$\{/g, '\\${')
    .replace(/\n/g, '\\n')
    .replace(/\r/g, '\\r')
    .replace(/\t/g, '\\t');
  return `"${escaped}"`;
}

function nixName(name: string): string {
  return /^[A-Za-z_][A-Za-z0-9_'-]*$/.test(name) && !KEYWORDS.has(name) ? name : nixString(name);
}

// Nix floats need a dot before any exponent (`1.0e-7`, not `1e-7`).
function nixNumber(value: number): string {
  const text = String(value);
  return text.replace(/^(-?\d+)(e)/, '$1.0$2');
}

function isComposite(value: SettingValue): value is SettingValue[] | { [key: string]: SettingValue } {
  return typeof value === 'object' && value !== null && !(value instanceof NumberText);
}

function nixExpr(value: SettingValue, indent: string): string {
  if (value === null) return 'null';
  if (typeof value === 'boolean') return String(value);
  if (typeof value === 'number') return nixNumber(value);
  if (typeof value === 'string') return nixString(value);
  if (value instanceof NumberText) return value.text;
  const inner = `${indent}  `;
  if (Array.isArray(value)) {
    if (!value.length) return '[ ]';
    // A leading minus would read as subtraction from the previous element.
    const items = value.map((item) => {
      const text = nixExpr(item, inner);
      return text.startsWith('-') ? `(${text})` : text;
    });
    if (!value.some(isComposite)) return `[ ${items.join(' ')} ]`;
    return `[\n${items.map((item) => `${inner}${item}\n`).join('')}${indent}]`;
  }
  const entries = Object.entries(value);
  if (!entries.length) return '{ }';
  return `{\n${entries.map(([key, entry]) => `${inner}${nixName(key)} = ${nixExpr(entry, inner)};\n`).join('')}${indent}}`;
}

/** A Nix expression for `value`. */
export function nixValue(value: SettingValue): string {
  return nixExpr(value, '');
}

/** Home Manager's `programs.btmux.settings` for a config.toml's contents. */
export function homeManagerSettings(settings: { [key: string]: SettingValue }): string {
  return `# Settings generated by btmux\nprograms.btmux.settings = ${nixValue(settings)};`;
}
