import { expect, test } from 'bun:test';
import { homeManagerSettings, nixValue, NumberText, type SettingValue } from './src/lib/nixSettings';
import { createShaderLayer, wallpaperLayerSettings } from './src/lib/wallpaperCatalog';

const settings: { [key: string]: SettingValue } = {
  prefix: 'C-b',
  shell: '/bin/fish -c "echo ${HOME} $${x} $$ \\ \n\t\r"',
  'wallpaper-opacity': new NumberText('0.50'),
  'window-grid-count': 6,
  'wallpaper-shader': [
    {
      ...wallpaperLayerSettings({ ...createShaderLayer('aurora'), enabled: false, opacity: 0.5 }),
      params: { stops: [[1, -0.5, 1e-7], { 'a b': true, if: null }], '1st': -2, e: 1e21 },
    },
  ],
  keys: { 'split-vertical': 'v', "it's": 'x' },
  terminal: { 'font-size': new NumberText('16.0'), 'cursor-blink': false },
  empty: {},
  none: [],
};

test('renders Home Manager settings', () => {
  expect(homeManagerSettings({})).toBe('# Settings generated by btmux\nprograms.btmux.settings = { };');
  expect(homeManagerSettings({ prefix: 'C-b', terminal: { 'font-size': new NumberText('16.0') } })).toBe(
    [
      '# Settings generated by btmux',
      'programs.btmux.settings = {',
      '  prefix = "C-b";',
      '  terminal = {',
      '    font-size = 16.0;',
      '  };',
      '};',
    ].join('\n'),
  );
  expect(nixValue([1, -2, 'a'])).toBe('[ 1 (-2) "a" ]');
  expect(nixValue({ if: 1, '1st': 2, "it's": 3 })).toBe('{\n  "if" = 1;\n  "1st" = 2;\n  it\'s = 3;\n}');
  expect(nixValue([1e-7, 1.5e-7, 1e21])).toBe('[ 1.0e-7 1.5e-7 1.0e+21 ]');
  expect(nixValue('${x} \\ "')).toBe('"\\${x} \\\\ \\""');
});

const plain = (value: SettingValue): unknown =>
  value instanceof NumberText
    ? Number(value.text)
    : Array.isArray(value)
      ? value.map(plain)
      : value && typeof value === 'object'
        ? Object.fromEntries(Object.entries(value).map(([key, entry]) => [key, plain(entry)]))
        : value;

test.if(Bun.which('nix-instantiate') !== null)('Nix evaluates to the same values', () => {
  const run = Bun.spawnSync(['nix-instantiate', '--eval', '--strict', '--json', '-E', nixValue(settings)]);
  expect(run.stderr.toString()).toBe('');
  expect(JSON.parse(run.stdout.toString())).toEqual(plain(settings));
});
